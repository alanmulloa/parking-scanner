import {
  ANON_KEY,
  SUPABASE_URL,
  assert,
  countRows,
  expectRpcError,
  isoDate,
  randomPassword,
  section,
  service,
  shortRunId,
  signIn,
} from './_common.mjs';

const runId = shortRunId();
const tag = `PREPROD_TEST_${runId}`;
const created = {
  users: [], dwellings: [], vehicles: [], requests: [], incidents: [], temporaries: [],
};
const trackedTables = [
  'profiles','community_members','dwellings','vehicles','temporary_periods','requests',
  'incidents','incident_followups','qr_controls','plate_controls','audit_log',
];
let baselineCounts = null;

async function snapshotCounts() {
  const result = {};
  for (const table of trackedTables) result[table] = await countRows(table);
  return result;
}

async function createUser(role) {
  const email = `preprod-test+${role.toLowerCase()}-${runId}@example.invalid`;
  const password = randomPassword();
  const { data, error } = await service.auth.admin.createUser({
    email,
    password,
    email_confirm: true,
    user_metadata: { purpose: 'parking-preproduction-test', run_id: runId },
  });
  if (error) throw error;
  const user = data.user;
  created.users.push(user.id);

  const { error: profileError } = await service.from('profiles').upsert({
    user_id: user.id,
    legacy_id: `${tag}_USER_${role}`,
    email,
    name: `PREPROD TEST ${role}`,
    phone: '',
    state: 'Activo',
    is_root: false,
  });
  if (profileError) throw profileError;

  return { id: user.id, email, password, role };
}

async function cleanup() {
  section('LIMPIEZA AUTOMATICA');
  try {
    if (created.users.length) {
      await service.from('qr_controls').delete().in('user_id', created.users);
      await service.from('plate_controls').delete().in('user_id', created.users);
      await service.from('audit_log').delete().in('actor_user_id', created.users);
    }
    if (created.incidents.length) await service.from('incident_followups').delete().in('incident_id', created.incidents);
    if (created.incidents.length) await service.from('incidents').delete().in('id', created.incidents);
    if (created.requests.length) await service.from('requests').delete().in('id', created.requests);
    if (created.temporaries.length) await service.from('temporary_periods').delete().in('id', created.temporaries);
    if (created.vehicles.length) await service.from('vehicles').delete().in('id', created.vehicles);
    if (created.dwellings.length) await service.from('dwellings').delete().in('id', created.dwellings);
    if (created.users.length) await service.from('community_members').delete().in('user_id', created.users);
    if (created.users.length) await service.from('profiles').delete().in('user_id', created.users);
    for (const userId of [...created.users].reverse()) {
      await service.auth.admin.deleteUser(userId);
    }

    // Remove any audit generated by test entity ids after business operations.
    const entityIds = [...created.incidents, ...created.requests, ...created.temporaries, ...created.vehicles, ...created.dwellings];
    if (entityIds.length) await service.from('audit_log').delete().in('entity_id', entityIds);

    const dw = await countRows('dwellings', (q) => q.ilike('legacy_id', `${tag}%`));
    const veh = await countRows('vehicles', (q) => q.ilike('legacy_id', `${tag}%`));
    const prof = await countRows('profiles', (q) => q.ilike('email', `preprod-test+%-${runId}@example.invalid`));
    assert(dw === 0 && veh === 0 && prof === 0, 'Fixtures eliminados completamente', `dwellings=${dw}, vehicles=${veh}, profiles=${prof}`);

    if (baselineCounts) {
      const after = await snapshotCounts();
      const changed = trackedTables
        .filter((table) => after[table] !== baselineCounts[table])
        .map((table) => `${table}: antes=${baselineCounts[table]} después=${after[table]}`);
      assert(changed.length === 0, 'Conteos restaurados exactamente al estado previo', changed.join('\n  '));
    }
  } catch (error) {
    console.error('ERROR DE LIMPIEZA:', error);
    console.error(`Run ID para limpieza manual: ${runId}`);
    throw error;
  }
}

try {
  baselineCounts = await snapshotCounts();
  section(`FIXTURE AISLADO ${runId}`);
  const { data: community, error: communityError } = await service
    .from('communities').select('id,name').eq('state', 'Activo').order('created_at').limit(1).single();
  if (communityError) throw communityError;
  assert(!!community?.id, 'Comunidad activa encontrada');

  const admin = await createUser('ADMIN');
  const control = await createUser('CONTROL');
  const owner = await createUser('PROPIETARIO');

  const memberships = [admin, control, owner].map((u) => ({
    community_id: community.id,
    user_id: u.id,
    roles: [u.role],
    state: 'Activo',
  }));
  const { error: membershipError } = await service.from('community_members').insert(memberships);
  if (membershipError) throw membershipError;

  const { data: dwRows, error: dwellingError } = await service.from('dwellings').insert([
    {
      community_id: community.id,
      legacy_id: `${tag}_DW_OWNER`,
      block: 'TEST', floor: '0', apartment: 'A', display_name: `${tag} OWNER`,
      responsible_user_id: owner.id, state: 'Activo', observations: tag,
    },
    {
      community_id: community.id,
      legacy_id: `${tag}_DW_FOREIGN`,
      block: 'TEST', floor: '0', apartment: 'B', display_name: `${tag} FOREIGN`,
      responsible_user_id: admin.id, state: 'Activo', observations: tag,
    },
  ]).select();
  if (dwellingError) throw dwellingError;
  created.dwellings.push(...dwRows.map((d) => d.id));
  const [ownerDwelling, foreignDwelling] = dwRows;

  const adminClient = await signIn(admin.email, admin.password);
  const controlClient = await signIn(control.email, control.password);
  const ownerClient = await signIn(owner.email, owner.password);

  section('ROLES / RLS');
  const { data: ownerBootstrap, error: ownerBootError } = await ownerClient.rpc('app_bootstrap');
  if (ownerBootError) throw ownerBootError;
  assert(ownerBootstrap?.profile?.is_root === false, 'PROPIETARIO no es ROOT');

  const { data: ownDw } = await ownerClient.from('dwellings').select('id').eq('id', ownerDwelling.id);
  const { data: foreignDw } = await ownerClient.from('dwellings').select('id').eq('id', foreignDwelling.id);
  assert(ownDw?.length === 1, 'PROPIETARIO puede leer su vivienda');
  assert(foreignDw?.length === 0, 'PROPIETARIO no puede leer vivienda ajena');
  await expectRpcError(ownerClient, 'app_dashboard', {}, 'PROPIETARIO no puede abrir dashboard ADMIN');
  await expectRpcError(controlClient, 'app_dashboard', {}, 'CONTROL no puede abrir dashboard ADMIN');
  const { data: dashboard, error: dashError } = await adminClient.rpc('app_dashboard');
  if (dashError) throw dashError;
  assert(Number(dashboard?.housing ?? 0) >= 79, 'ADMIN puede abrir dashboard');
  await expectRpcError(adminClient, 'root_system_status', {}, 'ADMIN no puede ejecutar funciones ROOT');

  const { data: roots, error: rootsError } = await service.from('profiles').select('user_id').eq('is_root', true).limit(1);
  if (rootsError) throw rootsError;
  if (roots?.[0]?.user_id) {
    const { data: adminRootView, error: adminRootError } = await adminClient.from('profiles').select('user_id').eq('user_id', roots[0].user_id);
    if (adminRootError) throw adminRootError;
    assert(adminRootView.length === 0, 'ADMIN no puede ver el perfil ROOT');
  }

  section('VEHICULOS / SLOTS / MOTO');
  async function ownerVehicle(suffix, type = 'Particular') {
    const payload = {
      ID_Vivienda: ownerDwelling.id,
      MatriculaHabitual: `T${runId.slice(-5)}${suffix}`,
      Marca: 'TEST', Modelo: suffix, Tipo: type, Observaciones: tag,
    };
    const { data, error } = await ownerClient.rpc('save_parking_vehicle', { p_payload: payload });
    if (error) throw error;
    created.vehicles.push(data.id);
    return data;
  }

  const car1 = await ownerVehicle('A');
  const car2 = await ownerVehicle('B');
  const car3 = await ownerVehicle('C');
  const moto = await ownerVehicle('M', 'Moto');
  assert(car1.slot === 1 && car1.state === 'Activo' && car1.qr_state === 'Activo' && !!car1.qr_token, 'Primer coche obtiene Slot 1 + QR');
  assert(car2.slot === 2 && car2.state === 'Activo' && car2.qr_state === 'Activo' && !!car2.qr_token, 'Segundo coche obtiene Slot 2 + QR');
  assert(car3.slot == null && car3.state === 'Desasignado' && !car3.qr_token, 'Tercer coche queda Desasignado sin QR');
  assert(moto.slot == null && moto.state === 'Activo' && !moto.qr_token && moto.qr_state == null, 'Moto queda Activa sin slot ni QR');

  const { data: controlWriteRows, error: controlWriteError } = await controlClient
    .from('vehicles')
    .update({ make: 'NO_DEBE_CAMBIAR' })
    .eq('id', car2.id)
    .select('id,make');
  const { data: car2Unchanged, error: car2UnchangedError } = await service
    .from('vehicles').select('make').eq('id', car2.id).single();
  if (car2UnchangedError) throw car2UnchangedError;
  assert(
    !!controlWriteError || (controlWriteRows?.length ?? 0) === 0,
    'CONTROL no puede editar vehículos directamente'
  );
  assert(car2Unchanged.make === car2.make, 'Intento CONTROL no modifica el vehículo');

  section('TEMPORAL MISMO DIA + ANULACION');
  const today = isoDate(0);
  const { data: temp, error: tempError } = await ownerClient.from('temporary_periods').insert({
    community_id: community.id,
    vehicle_id: car1.id,
    temporary_plate: `TMP${runId.slice(-5)}`,
    starts_at: today,
    ends_at: today,
    state: 'Activo',
    created_by: owner.id,
    observations: tag,
  }).select().single();
  if (tempError) throw tempError;
  created.temporaries.push(temp.id);
  assert(temp.starts_at === temp.ends_at, 'Temporal de un solo día permitido');

  const { data: car1Low, error: car1LowError } = await ownerClient.rpc('save_parking_vehicle', {
    p_payload: { ID_Vehiculo: car1.id, MatriculaHabitual: car1.habitual_plate, Estado: 'Desasignado' },
  });
  if (car1LowError) throw car1LowError;
  assert(car1Low.state === 'Desasignado', 'PROPIETARIO puede dejar su coche Desasignado');
  const { data: tempAfter, error: tempAfterError } = await service.from('temporary_periods').select('state').eq('id', temp.id).single();
  if (tempAfterError) throw tempAfterError;
  assert(tempAfter.state === 'Anulado', 'Temporal vigente se anula al dejar de estar Activo');

  section('SOLICITUD RENOVACION QR');
  const oldQr = car2.qr_token;
  const { error: revokeError } = await adminClient.from('vehicles').update({ qr_state: 'Revocado' }).eq('id', car2.id);
  if (revokeError) throw revokeError;
  const { data: request, error: reqError } = await ownerClient.rpc('create_parking_request', {
    p_vehicle_id: car2.id,
    p_type: 'RENOVACION_QR',
    p_reason: '',
    p_start_date: null,
    p_end_date: null,
  });
  if (reqError) throw reqError;
  created.requests.push(request.id);
  assert(request.state === 'Abierta', 'PROPIETARIO crea solicitud de renovación');
  const { data: resolved, error: resolveError } = await adminClient.rpc('resolve_parking_request', {
    p_request_id: request.id, p_decision: 'Aprobada', p_notes: 'PREPROD TEST',
  });
  if (resolveError) throw resolveError;
  assert(resolved.state === 'Aprobada', 'ADMIN aprueba solicitud');
  const { data: car2After, error: car2AfterError } = await service.from('vehicles').select('qr_token,qr_state').eq('id', car2.id).single();
  if (car2AfterError) throw car2AfterError;
  assert(car2After.qr_state === 'Activo' && car2After.qr_token && car2After.qr_token !== oldQr, 'Renovación genera QR nuevo y activo');

  section('SCANNER CONTROL');
  const { data: qrResult, error: qrError } = await controlClient.rpc('resolve_parking_control', { p_kind: 'QR', p_value: car2After.qr_token });
  if (qrError) throw qrError;
  assert(qrResult.status === 'AUTORIZADO', 'CONTROL resuelve QR TEST como AUTORIZADO', qrResult.status);
  const { data: plateResult, error: plateError } = await controlClient.rpc('resolve_parking_control', { p_kind: 'MATRICULA', p_value: car2.habitual_plate });
  if (plateError) throw plateError;
  assert(plateResult.status === 'AUTORIZADO', 'CONTROL resuelve matrícula TEST como AUTORIZADO', plateResult.status);
  await expectRpcError(ownerClient, 'resolve_parking_control', { p_kind: 'QR', p_value: car2After.qr_token }, 'PROPIETARIO no puede operar scanner');

  section('INCIDENCIA SOBRE FIXTURES');
  const { data: foreignVehicle, error: foreignVehicleError } = await adminClient.rpc('save_parking_vehicle', {
    p_payload: {
      ID_Vivienda: foreignDwelling.id,
      MatriculaHabitual: `F${runId.slice(-5)}Z`,
      Marca: 'TEST', Modelo: 'FOREIGN', Tipo: 'Particular', Observaciones: tag,
    },
  });
  if (foreignVehicleError) throw foreignVehicleError;
  created.vehicles.push(foreignVehicle.id);

  const candidate = {
    vehicle_id: foreignVehicle.id,
    dwelling_id: foreignDwelling.id,
    related_vehicle_id: car2.id,
    related_dwelling_id: ownerDwelling.id,
    observed_plate: foreignVehicle.habitual_plate,
    infraction_plate: foreignVehicle.habitual_plate,
    authorized_plate: car2.habitual_plate,
    related_plate: car2.habitual_plate,
    type: 'QR no corresponde con matrícula',
    situation: 'QR de otro vehículo',
    control_origin: 'QR',
    origin_state: 'AUTORIZADO',
    description: `${tag} incidencia sintética`,
    photo_url: `https://example.invalid/${tag}.jpg`,
    event_id: `${tag}_EVENT`,
  };
  const { data: incidentResult, error: incidentError } = await controlClient.rpc('save_parking_incident_candidates', {
    p_community_id: community.id,
    p_candidates: [candidate],
  });
  if (incidentError) throw incidentError;
  const incidentCreated = Array.isArray(incidentResult?.created) ? incidentResult.created : [];
  created.incidents.push(...incidentCreated.map((i) => i.id));
  assert(incidentResult?.mode === 'CREATED' && incidentCreated.length === 1, 'CONTROL registra incidencia TEST vinculada');

  section('RESULTADO');
  console.log(`Run ID: ${runId}`);
  console.log('PREPRODUCTION FIXTURE E2E: OK');
} finally {
  await cleanup();
}
